/**
 * Score all fake bird names for plausibility and regenerate the fake bird
 * portion of the CDN manifest.
 *
 * Usage:
 *   npx tsx scripts/score-fake-birds.ts
 *   npx tsx scripts/score-fake-birds.ts --preview   # print scores without writing manifest
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { scorePlausibility } from './lib/plausibility';

const __dirname = new URL('.', import.meta.url).pathname.replace(/\/$/, '');
const MANIFEST_PATH = join(__dirname, '..', 'src', 'lib', 'server', 'cdn-manifest.ts');
const FAKE_BIRDS_PATH = join(__dirname, 'data', 'fake-birds.json');

function slugify(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-') || 'unknown-bird';
}

// ---------------------------------------------------------------------------
// Read the existing real-bird Set from the manifest so we preserve it
// ---------------------------------------------------------------------------

function readExistingRealBirdBlock(): string {
  if (!existsSync(MANIFEST_PATH)) {
    return `const CDN_BIRD_KEYS: ReadonlySet<string> = new Set([]);`;
  }

  const content = readFileSync(MANIFEST_PATH, 'utf-8');

  // Extract everything from "const CDN_BIRD_KEYS" up to and including the closing "]);".
  const match = content.match(/(const CDN_BIRD_KEYS: ReadonlySet<string> = new Set\(\[[\s\S]*?\]\);)/);
  if (!match) {
    throw new Error('Could not find CDN_BIRD_KEYS block in existing manifest');
  }

  return match[1];
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

const isPreview = process.argv.includes('--preview');

const fakeBirdNames: string[] = JSON.parse(readFileSync(FAKE_BIRDS_PATH, 'utf-8'));

const scored = fakeBirdNames.map((name) => ({
  name,
  key: slugify(name),
  plausibility: scorePlausibility(name),
}));

// Sort by key for deterministic manifest output
scored.sort((a, b) => a.key.localeCompare(b.key));

// Print distribution summary
const distribution: Record<number, number> = {};
for (const { plausibility } of scored) {
  distribution[plausibility] = (distribution[plausibility] ?? 0) + 1;
}

console.log(`Scored ${scored.length} fake birds.\n`);
console.log('Plausibility distribution:');
for (let i = 1; i <= 10; i++) {
  const count = distribution[i] ?? 0;
  const bar = '█'.repeat(Math.ceil(count / 5));
  console.log(`  ${i.toString().padStart(2)}: ${count.toString().padStart(4)}  ${bar}`);
}
console.log('');

if (isPreview) {
  // In preview mode, print a sample from each bucket
  for (let i = 1; i <= 10; i++) {
    const bucket = scored.filter((s) => s.plausibility === i);
    if (bucket.length === 0) continue;
    const sample = bucket.slice(0, 3).map((s) => s.name).join(', ');
    const more = bucket.length > 3 ? ` (+${bucket.length - 3} more)` : '';
    console.log(`  [${i}] ${sample}${more}`);
  }
  console.log('\nPreview only — manifest not updated.');
  process.exit(0);
}

// ---------------------------------------------------------------------------
// Generate manifest
// ---------------------------------------------------------------------------

const realBirdBlock = readExistingRealBirdBlock();

const fakeBirdEntries = scored
  .map((s) => `  ['${s.key}', { plausibility: ${s.plausibility} }],`)
  .join('\n');

const manifest = `// Auto-generated — do not edit manually
// Real birds: generated by scripts/seed-cdn.ts
// Fake birds: scored by scripts/score-fake-birds.ts

${realBirdBlock}

const CDN_FAKE_BIRDS: ReadonlyMap<string, { plausibility: number }> = new Map([
${fakeBirdEntries}
]);

export function hasCdnAssets(birdKey: string): boolean {
  return CDN_BIRD_KEYS.has(birdKey);
}

export function getCdnBirdKeys(): ReadonlySet<string> {
  return CDN_BIRD_KEYS;
}

export function hasFakeCdnAssets(birdKey: string): boolean {
  return CDN_FAKE_BIRDS.has(birdKey);
}

export function getCdnFakeBirdKeys(): ReadonlySet<string> {
  return new Set(CDN_FAKE_BIRDS.keys());
}

export function getFakeBirdPlausibility(birdKey: string): number | undefined {
  return CDN_FAKE_BIRDS.get(birdKey)?.plausibility;
}

export function getFakeBirdsByPlausibilityRange(min: number, max: number): string[] {
  const results: string[] = [];
  for (const [key, { plausibility }] of CDN_FAKE_BIRDS) {
    if (plausibility >= min && plausibility <= max) {
      results.push(key);
    }
  }
  return results;
}
`;

writeFileSync(MANIFEST_PATH, manifest, 'utf-8');
console.log(`Wrote manifest to src/lib/server/cdn-manifest.ts`);
console.log(`  Real birds: preserved from existing manifest`);
console.log(`  Fake birds: ${scored.length} entries with plausibility scores`);
